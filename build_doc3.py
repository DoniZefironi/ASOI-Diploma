# ── Helpers ───────────────────────────────────────────────────────────────────
def heading(text):
    """All section headings use Heading 2 as in the template"""
    p = doc.add_paragraph(style='Heading 2')
    p.clear()
    run = p.add_run(text)
    return p

def body(text):
    p = doc.add_paragraph(style='Normal')
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.add_run(text)
    return p

def body_noi(text):
    """Body without first-line indent — 'Мой абзац' equivalent"""
    p = doc.add_paragraph(style='Normal')
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Pt(0)
    p.add_run(text)
    return p

def li(text):
    p = doc.add_paragraph(style='List Paragraph')
    p.add_run(text)
    return p

def fig(n, caption):
    """Image placeholder"""
    p = doc.add_paragraph(style='Normal')
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(6)
    run = p.add_run(f'Рисунок {n} – {caption}')
    run.italic = True
    return p

def tbl_caption(text):
    p = doc.add_paragraph(style='Normal')
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.space_before = Pt(8)
    run = p.add_run(text)
    run.bold = True
    return p

def usecase_table(num, name, actor, pre, main_flow, alt_flow, post):
    """Use-case table matching Gymside template style"""
    tbl_caption(f'Таблица {num} – {name}')
    t = doc.add_table(rows=6, cols=2)
    t.style = 'Table Grid'
    data = [
        ('Название', name),
        ('Действующее лицо', actor),
        ('Предусловие', pre),
        ('Основной поток', main_flow),
        ('Альтернативный поток', alt_flow),
        ('Постусловие', post),
    ]
    for i, (label, val) in enumerate(data):
        row = t.rows[i]
        row.cells[0].text = label
        row.cells[0].paragraphs[0].runs[0].bold = True
        row.cells[0].width = Cm(5.0)
        row.cells[1].text = val
        row.cells[1].width = Cm(11.8)
        for cell in row.cells:
            for para in cell.paragraphs:
                para.paragraph_format.space_before = Pt(2)
                para.paragraph_format.space_after = Pt(2)
    doc.add_paragraph()

def entity_table(num, name, rows):
    """Entity table for section 2.3"""
    tbl_caption(f'Таблица {num} – Структура таблицы {name}')
    t = doc.add_table(rows=1 + len(rows), cols=3)
    t.style = 'Table Grid'
    headers = ['Поле', 'Тип данных', 'Описание']
    for i, h in enumerate(headers):
        t.rows[0].cells[i].text = h
        t.rows[0].cells[i].paragraphs[0].runs[0].bold = True
        t.rows[0].cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    widths = [Cm(4.5), Cm(4.0), Cm(8.3)]
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            t.rows[ri+1].cells[ci].text = str(val)
            t.rows[ri+1].cells[ci].width = widths[ci]
    for ci, cell in enumerate(t.rows[0].cells):
        cell.width = widths[ci] if ci < 3 else Cm(4.0)
    doc.add_paragraph()

def pb():
    doc.add_page_break()

